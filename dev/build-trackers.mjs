// Generates src/trackers-data.js from the two open-source lists in vendor/:
//   - Simplify Gmail tracker blocklist (BSD-3-Clause), company names + regexes
//   - Trocker open-tracker list (Apache-2.0), short codes + domains
// The vendored files are parsed as text, never executed.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const read = (f) => readFileSync(`${root}vendor/${f}`, 'utf8');

// Simplify: `const trackers = { "Company": "regex" | ["regex", ...], ... };`
function parseSimplify(src) {
  const body = src.match(/const trackers = (\{[\s\S]*?\n\});/)[1]
    .replace(/(^|[,[{])\s*\/\/.*$/gm, '$1')
    .replace(/^(\s*)([A-Za-z_][\w]*)\s*:/gm, '$1"$2":') // a few keys are unquoted
    .replace(/,(\s*[\]}])/g, '$1');
  return JSON.parse(body);
}

// Trocker: the array inside getOpenTrackerList, as `{ name: 'XX', domains: ['a', 'b'], ... }`.
function parseTrocker(src) {
  const start = src.indexOf('export async function getOpenTrackerList');
  const end = src.indexOf('export async function', start + 10);
  const block = src.slice(start, end);
  return [...block.matchAll(/name:\s*'([^']+)',\s*domains:\s*\[([^\]]*)\]/g)].map(([, name, domains]) => ({
    name,
    domains: [...domains.matchAll(/'([^']+)'/g)].map((m) => m[1]),
  }));
}

const TROCKER_NAMES = {
  YW: 'Yesware', SK: 'HubSpot Sales', MT: 'Mailtrack', MC: 'Mailchimp', SG: 'SendGrid',
  IC: 'iContact', BT: 'Bananatag', MM: 'Mixmax', CC: 'Constant Contact', PM: 'Postmark',
  KV: 'Klaviyo', SV: 'StrongView', IB: 'IBM Marketing Cloud',
};
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

const list = [];
const add = (name, source) => {
  try {
    new RegExp(source, 'i');
    list.push({ name, source });
  } catch {
    console.warn(`skipped invalid pattern for ${name}: ${source}`);
  }
};

// Our own additions, seen in real newsletters.
add('Salesforce Marketing Cloud', '\\/open\\.aspx\\?'); // sent from the brand's own domain
add('Amazon SES', 'awstrack\\.me\\/I0\\/');

for (const [company, patterns] of Object.entries(parseSimplify(read('simplify-tracker-blocklist.js')))) {
  const name = company.replace(/\.(com|net)$/i, ''); // keeps names like Customer.io
  for (const p of [patterns].flat()) add(name, p);
}
for (const t of parseTrocker(read('trocker-lists.js'))) {
  const name = TROCKER_NAMES[t.name] || 'Email tracker';
  for (const d of t.domains) add(name, escape(d));
}

const header = `// Generated by dev/build-trackers.mjs. Do not edit by hand.
// Sources: Simplify tracker blocklist (BSD-3-Clause, (c) Michael Leggett) and
// Trocker (Apache-2.0). See THIRD_PARTY_NOTICES.md.
`;
writeFileSync(`${root}src/trackers-data.js`, `${header}const TRACKER_LIST = ${JSON.stringify(list, null, 1)};\n`);
console.log(`${list.length} patterns, ${new Set(list.map((t) => t.name)).size} companies`);
